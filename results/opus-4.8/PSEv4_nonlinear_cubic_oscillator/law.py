"""Discovered law for predicting dv_dt.

The data are generated by a nonlinear oscillator with a cubic (Duffing-type)
restoring force and amplitude-dependent (position-dependent) linear damping:

    dv/dt = -beta * x**3  -  gamma(x) * v ,   gamma(x) = g0 / (1 + a * x**2)

Fitted parameters (see explain.md):
    beta = 2.25
    g0   = 0.67237     (damping coefficient at x = 0)
    a    = 0.44406     (how fast damping falls off with amplitude)
"""

BETA = 2.25
G0 = 0.67236965
A = 0.44405520


def law(input_data: list[dict[str, float]]) -> list[dict[str, float]]:
    out = []
    for row in input_data:
        x = row["x"]
        v = row["v"]
        gamma = G0 / (1.0 + A * x * x)
        dv_dt = -BETA * x ** 3 - gamma * v
        out.append({"dv_dt": dv_dt})
    return out
