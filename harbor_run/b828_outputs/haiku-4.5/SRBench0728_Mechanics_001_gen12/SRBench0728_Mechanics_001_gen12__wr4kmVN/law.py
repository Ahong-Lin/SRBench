def law(input_data: list[dict[str, float]]) -> list[dict[str, float]]:
    """
    Predict dv_dt (instantaneous acceleration) using a degree-3 polynomial model.

    The relationship is discovered through polynomial feature regression on the training data.
    """
    results = []

    for row in input_data:
        t = row['t']
        x = row['x']
        v = row['v']
        Fh = row['Fh']
        Fh2 = row['Fh2']

        # Degree 3 polynomial fit coefficients (from sklearn PolynomialFeatures)
        dv_dt = -0.076858470903 + (
            -0.593049342970 * x
            - 0.372028182604 * (x**3)
            - 0.225151919358 * Fh
            - 0.199404914482 * (x * v**2)
            + 0.156040341439 * (t * x * Fh2)
            - 0.136641719451 * (v**3)
            - 0.126444656580 * (v**2 * Fh)
            + 0.073143161549 * (v * Fh**2)
            + 0.069764727378 * (t * Fh * Fh2)
            - 0.068683835143 * (x**2 * v)
            + 0.061257576389 * (x * Fh)
            - 0.058214554160 * Fh2
            + 0.052424980864 * (t * Fh)
            + 0.045660284383 * (x * Fh2**2)
            + 0.043560954212 * (x * Fh * Fh2)
            + 0.040333330025 * (v * Fh)
            - 0.039929148777 * (t * x * Fh)
            + 0.038802384166 * (x * Fh2)
            + 0.037797987092 * (x * v * Fh)
            + 0.033534976171 * (t * x * v)
            + 0.031913906132 * (v**2)
            - 0.030214356107 * (t * Fh**2)
            + 0.029768962285 * (t * v * Fh2)
            - 0.029026973481 * v
            - 0.027681718125 * (Fh**2)
            + 0.027245284147 * (t * x**2)
            - 0.025291794802 * (x * v * Fh2)
            - 0.024257541506 * (t * x)
            + 0.023798648830 * (t * v**2)
            + 0.023664308301 * (Fh**2 * Fh2)
            + 0.020903782493 * (Fh * Fh2)
            - 0.020819767328 * (x**2 * Fh)
            + 0.020442232375 * (x * v)
            + 0.018774944788 * (v * Fh * Fh2)
            + 0.018764439735 * (x**2 * Fh2)
            + 0.018412076957 * (Fh2**2)
            + 0.018049477896 * (v * Fh2**2)
            - 0.017963223819 * (v**2 * Fh2)
            - 0.017337630264 * (v * Fh2)
            + 0.016436156616 * (t * v)
            - 0.015294321001 * (t * Fh2)
            + 0.011191394256 * (t * v * Fh)
            + 0.010101898448 * (Fh * Fh2**2)
            - 0.009636844389 * (t**2 * Fh2)
            + 0.009247437055 * (t * Fh2**2)
            - 0.007177281178 * (x**2)
            + 0.006954013086 * (Fh**3)
            - 0.005864993060 * (Fh2**3)
            - 0.004229662570 * (x * Fh**2)
            - 0.003235769903 * (t**2 * v)
            - 0.001627331422 * (t**2)
            - 0.000986064942 * t
            + 0.000888806034 * (t**2 * x)
            + 0.000480549850 * (t**2 * Fh)
            + 0.000033169324 * (t**3)
        )

        results.append({"dv_dt": dv_dt})

    return results
