"""Discovered instantaneous acceleration law.

The data are generated by a driven, damped, nonlinear (hardening) oscillator:

    dv/dt = A*sin(w*t)  -  c*sin(v)  -  R(x)

where
  * A*sin(w*t)  is a sinusoidal external drive with w = 1,
  * c*sin(v)    is a weak nonlinear (velocity) damping term,
  * R(x)        is an odd, hardening restoring force, represented by the
                fitted odd polynomial  R(x) = a1*x + a3*x^3 + ... + a9*x^9.

All parameters were inferred from the training data by least squares.
Each row is mapped independently; no state is carried between calls.
"""

import math

# Drive: A*sin(w*t), w = 1
A = 1.1975813217200704
W = 1.0

# Nonlinear damping: -D*sin(v)
D = 0.2993998510377894

# Hardening restoring force R(x) = sum a_k x^k (odd powers)
X_POWERS = (1, 3, 5, 7, 9)
X_COEFFS = (
    -0.7919713962960969,
    -0.17236582340935613,
    -0.5685745735753579,
    0.19803738297226345,
    -0.026031813707994542,
)


def _dv_dt(t: float, x: float, v: float) -> float:
    drive = A * math.sin(W * t)
    damping = -D * math.sin(v)
    restoring = 0.0
    for k, a in zip(X_POWERS, X_COEFFS):
        restoring += a * x ** k
    return drive + damping + restoring


def law(input_data: list[dict[str, float]]) -> list[dict[str, float]]:
    out = []
    for row in input_data:
        t = float(row["t"])
        x = float(row["x"])
        v = float(row["v"])
        out.append({"dv_dt": _dv_dt(t, x, v)})
    return out


if __name__ == "__main__":
    import pandas as pd

    df = pd.read_csv("/app/data/train_data.csv")
    preds = law(df[["t", "x", "v"]].to_dict("records"))
    p = [d["dv_dt"] for d in preds]
    err = [(a - b) for a, b in zip(p, df["dv_dt"].tolist())]
    rms = (sum(e * e for e in err) / len(err)) ** 0.5
    print("rms", rms, "max", max(abs(e) for e in err))
